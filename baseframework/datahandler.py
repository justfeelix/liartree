import numpy as np
from sklearn.preprocessing import MinMaxScaler
from pathlib import Path

# Get the directory where this file is located
DATA_DIR = Path(__file__).parent / "data"

def read_file(dsname):
    if dsname == "har": # UCI: DOI:10.24432/C54S4K, Jorge Reyes-Ortiz, Davide Anguita, Alessandro Ghio, Luca Oneto, Xavier Parra, licensed under a Creative Commons Attribution 4.0 International (CC BY 4.0) license.
        X = np.load(DATA_DIR / "HAR_data.npy", allow_pickle=True)
        y = np.load(DATA_DIR / "HAR_label.npy", allow_pickle=True)
        y = y.reshape(1, len(y))[0]
        return X, y
    elif dsname == "stream_densired": # own
        X = np.load(DATA_DIR / "stream_densired_data.npy", allow_pickle=True)
        y = np.load(DATA_DIR / "stream_densired_label.npy", allow_pickle=True)
        y = y.reshape(1, len(y))[0]
        return X, y
    elif dsname == "rbf3": # from https://github.com/CIG-UFSCar/DS_Datasets
        X = np.load(DATA_DIR / "rbf3_data.npy", allow_pickle=True)
        y = np.load(DATA_DIR / "rbf3_label.npy", allow_pickle=True)
        y = y.reshape(1, len(y))[0]
        return X, y
    elif dsname == "complex9": # from https://github.com/deric/clustering-benchmark
        X = np.load(DATA_DIR / "complex9_data.npy", allow_pickle=True)
        y = np.load(DATA_DIR / "complex9_label.npy", allow_pickle=True)
        y = y.reshape(1, len(y))[0]
        return X, y
    else:
        # Generic fallback: load any {dsname}_data.npy / {dsname}_label.npy
        # from DATA_DIR (e.g. noise variants generated by gen_data.ipynb).
        data_path  = DATA_DIR / f"{dsname}_data.npy"
        label_path = DATA_DIR / f"{dsname}_label.npy"
        if data_path.exists() and label_path.exists():
            X = np.load(data_path,  allow_pickle=True)
            y = np.load(label_path, allow_pickle=True)
            y = y.reshape(1, len(y))[0]
            return X, y
        raise FileNotFoundError

def load_data(dsname, batch=None, batch_max=None, scale=True):
    X, y = read_file(dsname)
    X = X.astype(np.double)
    if scale:
        scaler = MinMaxScaler()
        X = scaler.fit_transform(X)

    if batch is not None and batch_max is not None:
        X = X[:batch*batch_max]
        y = y[:batch*batch_max]
    return X, y

if __name__ == "__main__":
    for ds in ["complex9", "stream_densired", "rbf3", "har"]:
         data, label = load_data(ds)
         print(f"{ds}: N: {len(label)}, d: {data.shape[1]}, k: {len(np.unique(label))}")

